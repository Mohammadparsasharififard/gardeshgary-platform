import { useCallback, useEffect } from 'react';
import { useLocalStorage } from './useLocalStorage';
import { useAuth } from './useAuth';
import { dataLoaders } from '@/lib/loaders';

export interface AppNotification {
  id: string;
  title: string;
  body: string;
  type: 'info' | 'success' | 'warning' | 'law-update';
  timestamp: number;
  read: boolean;
  /** Optional link target (e.g. '#calculator') */
  href?: string;
}

const STORAGE_KEY = 'gardeshgary.notifications.v1';

/** Seed notifications shown to first-time (logged-out) users */
const SEED: AppNotification[] = [
  {
    id: 'n1',
    title: 'به‌روزرسانی قوانین',
    body: 'بخشنامه جدید سازمان هواپیمایی در خصوص غرامت تأخیر پرواز اضافه شد.',
    type: 'law-update',
    timestamp: Date.now() - 1000 * 60 * 30,
    read: false,
    href: '#/laws',
  },
  {
    id: 'n2',
    title: 'خوش آمدید',
    body: 'به پلتفرم ملی حقوق گردشگری خوش آمدید. برای شروع، جستجوی هوشمند را امتحان کنید.',
    type: 'info',
    timestamp: Date.now() - 1000 * 60 * 60 * 2,
    read: false,
    href: '#/',
  },
];

/**
 * useNotifications — manages an in-app notification feed.
 *
 * - For logged-in users, loads real notifications from the backend
 *   (notifications generated by claims, bookings, status changes, etc.).
 * - For logged-out users, shows the static SEED list so the UI is never empty.
 * - Persists last-seen state in localStorage.
 */
export function useNotifications() {
  const { user } = useAuth();
  const [items, setItems] = useLocalStorage<AppNotification[]>(STORAGE_KEY, SEED);

  // When the user logs in (or changes), refresh notifications from the backend.
  // For logged-out users, fall back to the seed data.
  useEffect(() => {
    if (!user) {
      setItems(SEED);
      return;
    }
    let cancelled = false;
    void (async () => {
      const { data } = await dataLoaders.loadNotifications();
      if (cancelled) return;
      if (data && data.notifications.length >= 0) {
        // Map backend notifications to the AppNotification shape
        const mapped: AppNotification[] = data.notifications.map((n) => ({
          id: n.id,
          title: n.title,
          body: n.message,
          type: n.type.toLowerCase() as AppNotification['type'],
          timestamp: new Date(n.createdAt).getTime(),
          read: n.isRead,
          href: n.link || undefined,
        }));
        setItems(mapped);
      }
    })();
    return () => { cancelled = true; };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [user]);

  const unreadCount = items.filter((n) => !n.read).length;

  const markAllRead = useCallback(() => {
    setItems((prev) => prev.map((n) => ({ ...n, read: true })));
  }, [setItems]);

  const markRead = useCallback(async (id: string) => {
    setItems((prev) => prev.map((n) => (n.id === id ? { ...n, read: true } : n)));
    // Also persist to the backend (best-effort)
    if (user) {
      await dataLoaders.markNotificationRead(id);
    }
  }, [setItems, user]);

  const remove = useCallback((id: string) => {
    setItems((prev) => prev.filter((n) => n.id !== id));
  }, [setItems]);

  const clear = useCallback(() => {
    setItems([]);
  }, [setItems]);

  const push = useCallback(
    (n: Omit<AppNotification, 'id' | 'timestamp' | 'read'>) => {
      const id = `n${Date.now()}`;
      const next: AppNotification = { ...n, id, timestamp: Date.now(), read: false };
      setItems((prev) => [next, ...prev]);
      return id;
    },
    [setItems],
  );

  const requestOsPermission = useCallback(async (): Promise<NotificationPermission> => {
    if (typeof window === 'undefined' || !('Notification' in window)) {
      return 'denied';
    }
    if (Notification.permission === 'granted') return 'granted';
    if (Notification.permission === 'denied') return 'denied';
    try {
      return await Notification.requestPermission();
    } catch {
      return 'denied';
    }
  }, []);

  const sendOsNotification = useCallback(
    (title: string, body: string, href?: string) => {
      if (typeof window === 'undefined' || !('Notification' in window)) return;
      if (Notification.permission !== 'granted') return;
      try {
        const n = new Notification(title, {
          body,
          icon: '/favicon.svg',
          badge: '/favicon.svg',
          tag: 'gardeshgary',
        });
        if (href) {
          n.onclick = () => {
            window.focus();
            window.location.hash = href;
            n.close();
          };
        }
      } catch {
        /* notifications blocked or unsupported */
      }
    },
    [],
  );

  return {
    items,
    unreadCount,
    markAllRead,
    markRead,
    remove,
    clear,
    push,
    requestOsPermission,
    sendOsNotification,
  };
}

export default useNotifications;
